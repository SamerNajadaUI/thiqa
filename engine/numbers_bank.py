    animals_old = [q for q in old["حيوانات"] if not any(k in q[0] for k in body)]
    moved = [q for q in old["حيوانات"] if q not in animals_old]
    islamic = old["إسلامية"] + [[f"كم آية بسورة {n}؟", a, "آية", ""] for n, a in ISLAMIC_SURAH_AYAT] \
        + [[f"شو ترتيب سورة {n} بالمصحف؟", k, "", ""] for n, k in ISLAMIC_SURAH_ORDER] + ISLAMIC
    bank = {
        "رياضة": old["رياضة"] + SPORTS,
        "إسلامية": islamic,
        "حيوانات": animals_old + ANIMALS,
        "جغرافيا": old["جغرافيا"] + GEOGRAPHY,
        "تاريخ": HISTORY,
        "علوم وجسم الإنسان": moved + SCIENCE,
        "أرقام من حياتنا": LIFE,
    }
    problems = []
    seen = set()
    for cat, qs in bank.items():
        for q in qs:
            if len(q) != 4 or not isinstance(q[1], (int, float)) or q[1] < 0:
                problems.append((cat, q))
            if q[0] in seen:
                problems.append(("مكرر", q[0]))
            seen.add(q[0])
        print(f"{cat}: {len(qs)}")
    if problems:
        print("مشاكل:", problems)
        return 1
    short = [c for c, qs in bank.items() if len(qs) < 100]
    if short:
        print("أقسام أقل من 100:", short)
        return 1
    new = "const QUESTIONS = " + json.dumps(bank, ensure_ascii=False) + ";\n"
    PAGE.write_text(s[:m.start()] + new + s[m.end():], encoding="utf-8")
    print("المجموع:", sum(len(q) for q in bank.values()))
    return 0


